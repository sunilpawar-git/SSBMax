package com.ssbmax.shared.data.repository

import com.ssbmax.shared.domain.model.PIQSubmission
import com.ssbmax.shared.domain.model.SubmissionStatus
import kotlinx.serialization.Serializable

/**
 * Wire format for [PIQSubmission] — a ~90-field flat form model (personal/family/education/NCC/
 * interview-history sections), mirroring the Android `PIQSubmission.toMap()`/`parsePIQSubmission()`
 * pair (`core/data/remote/SubmissionMappers.kt`) field-for-field. Section DTOs live in
 * `PIQSubmissionSectionDtos.kt` to keep both files under the 300-line limit.
 *
 * **`aiPreliminaryScore` is written but never read back**, same real limitation as the Android
 * original: `PIQSubmission.toMap()` serializes it, but `parsePIQSubmission()` never reconstructs it
 * (no `"aiPreliminaryScore"` key in its `PIQSubmission(...)` call) — ported faithfully, not fixed,
 * matching this cluster's existing precedent (`OIRSubmission.testResult.answeredQuestions` has the
 * same kind of write-only gap in `GitLivePersonalTestSubmissionRepository`).
 */
@Serializable
internal data class PIQDataDto(
    val id: String = "",
    val userId: String = "",
    val testId: String = "piq_standard",
    val oirNumber: String = "",
    val selectionBoard: String = "",
    val batchNumber: String = "",
    val chestNumber: String = "",
    val upscRollNumber: String = "",
    val fullName: String = "",
    val dateOfBirth: String = "",
    val age: String = "",
    val gender: String = "",
    val phone: String = "",
    val email: String = "",
    val state: String = "",
    val district: String = "",
    val religion: String = "",
    val scStObcStatus: String = "",
    val motherTongue: String = "",
    val maritalStatus: String = "",
    val permanentAddress: String = "",
    val presentAddress: String = "",
    val maximumResidence: String = "",
    val maximumResidencePopulation: String = "",
    val presentResidencePopulation: String = "",
    val permanentResidencePopulation: String = "",
    val isDistrictHQ: Boolean = false,
    val height: String = "",
    val weight: String = "",
    val fatherName: String = "",
    val fatherOccupation: String = "",
    val fatherEducation: String = "",
    val fatherIncome: String = "",
    val motherName: String = "",
    val motherOccupation: String = "",
    val motherEducation: String = "",
    val parentsAlive: String = "",
    val ageAtFatherDeath: String = "",
    val ageAtMotherDeath: String = "",
    val guardianName: String = "",
    val guardianOccupation: String = "",
    val guardianEducation: String = "",
    val guardianIncome: String = "",
    val siblings: List<SiblingDto> = emptyList(),
    val presentOccupation: String = "",
    val personalMonthlyIncome: String = "",
    val education10th: EducationDto = EducationDto(level = "10th"),
    val education12th: EducationDto = EducationDto(level = "12th"),
    val educationGraduation: EducationDto = EducationDto(level = "Graduation"),
    val educationPostGraduation: EducationDto = EducationDto(level = "Post-Graduation"),
    val hobbies: String = "",
    val sports: String = "",
    val sportsParticipation: List<SportsParticipationDto> = emptyList(),
    val extraCurricularActivities: List<ExtraCurricularActivityDto> = emptyList(),
    val positionsOfResponsibility: String = "",
    val workExperience: List<WorkExperienceDto> = emptyList(),
    val nccTraining: NCCTrainingDto = NCCTrainingDto(),
    val natureOfCommission: String = "",
    val choiceOfService: String = "",
    val chancesAvailed: String = "",
    val previousInterviews: List<PreviousInterviewDto> = emptyList(),
    val whyDefenseForces: String = "",
    val strengths: String = "",
    val weaknesses: String = "",
    val status: String = "",
    val submittedAt: Long = 0L,
    val lastModifiedAt: Long = 0L,
    val gradedByInstructorId: String? = null,
    val gradingTimestamp: Long? = null,
    val aiPreliminaryScore: PIQAIScoreDto? = null
)

